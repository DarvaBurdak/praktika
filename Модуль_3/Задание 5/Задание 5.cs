using System;
// Создаём делегат для сортировки.
// Он может хранить ссылку на метод, который принимает массив int и ничего не возвращает.
delegate void SortDelegate(int[] array);
class Program
{
    // Метод сортировки пузырьком.
    static void BubbleSort(int[] array)
    {
        // Внешний цикл отвечает за количество проходов.
        // Начиная с первого, но не доходя до последнего элемента
        for (int i = 0; i < array.Length - 1; i++)
        {
            // Внутренний цикл сравнивает соседние элементы.
            // После каждого прохода самый большой элемент постепенно перемещается в конец массива.
            // Перебираем элементы массива слева направо, сравнивая соседние, причём с каждым новым проходом проверять на один элемент меньше
            for (int j = 0; j < array.Length - i - 1; j++)
            {
                // Проверяем, стоит ли левый элемент после правого.
                if (array[j] > array[j + 1])
                {
                    // Временная переменная нужна, чтобы не потерять значение элемента.
                    int temp = array[j];
                    // На место первого элемента ставим второй.
                    array[j] = array[j + 1];
                    // На место второго ставим сохранённый первый.
                    array[j + 1] = temp;
                }
            }
        }
    }
    // Метод быстрой сортировки.
    // left это левая граница части массива.
    // right — правая граница части массива.
    static void QuickSort(int[] array, int left, int right)
    {
        // Индекс начала рассматриваемой части массива.
        int i = left;
        // Индекс конца рассматриваемой части массива.
        int j = right;
        // Выбираем центральный элемент в качестве опорного.
        int pivot = array[(left + right) / 2];
        // Пока левая граница не пересеклась с правой.
        while (i <= j)
        {
            // Ищем элемент, который должен находиться справа от опорного.
            while (array[i] < pivot)
            {
                i++;
            }
            // Ищем элемент, который должен находиться слева от опорного.
            while (array[j] > pivot)
            {
                j--;
            }
            // Если индексы ещё не пересеклись, меняем элементы местами.
            if (i <= j)
            {
                // Сохраняем первый элемент.
                int temp = array[i];
                // Меняем элементы местами.
                array[i] = array[j];
                array[j] = temp;
                // Переходим к следующим элементам.
                i++;
                j--;
            }
        }
        // Рекурсивно сортируем левую часть массива.
        if (left < j)
        {
            QuickSort(array, left, j);
        }
        // Рекурсивно сортируем правую часть массива.
        if (i < right)
        {
            QuickSort(array, i, right);
        }
    }
    // Вспомогательный метод.
    // Он запускает быструю сортировку для всего массива.
    static void StartQuickSort(int[] array)
    {
        // Передаём первый и последний индексы массива.
        QuickSort(array, 0, array.Length - 1);
    }
    static void Main()
    {
        // Создаём объект Random для генерации случайных чисел.
        Random random = new Random();
        int[] numbers = new int[50];
        // Заполняем массив случайными числами.
        for (int i = 0; i < numbers.Length; i++)
        {
            numbers[i] = random.Next(1, 101);
        }
        // Выводим исходный массив.
        Console.WriteLine("Исходный массив:");

        for (int i = 0; i < numbers.Length; i++)
        {
            Console.Write(numbers[i] + " ");
        }
        Console.WriteLine();
        // Предлагаем пользователю выбрать сортировку.
        Console.WriteLine();
        Console.WriteLine("Выберите сортировку:");
        //сортировка пузырьком.
        Console.WriteLine("1 - Пузырьком");
        //быстрая сортировка.
        Console.WriteLine("2 - Быстрая сортировка");
        // Считываем выбор пользователя.
        int choice = Convert.ToInt32(Console.ReadLine());
        // Создаём переменную типа SortDelegate.
        SortDelegate sort;
        // В зависимости от выбора пользователя выбираем конкретный метод.
        if (choice == 1)
        {
            // Делегат будет хранить BubbleSort.
            sort = BubbleSort;
        }
        else
        {
            // Делегат будет хранить StartQuickSort.
            sort = StartQuickSort;
        }
        // Запускаем выбранный алгоритм сортировки через делегат.
        sort(numbers);
        // Выводим результат.
        Console.WriteLine();
        Console.WriteLine("Отсортированный массив:");
        foreach (int number in numbers)
        {
            Console.Write(number + " ");
        }
    }
}