using System;
namespace ContactsWPF
{
    // Класс Contact описывает один контакт в телефонной книге.
    // Каждый объект этого класса представляет отдельного человека.
    public class Contact
    {
        // Уникальный идентификатор контакта.
        // Он нужен, чтобы различать контакты, даже если у них одинаковые имена.
        public int Id { get; set; }
        // Имя и фамилия человека.
        // Свойство get позволяет получить имя, а set — изменить его.
        public string Name { get; set; }
        // Номер телефона человека.
        public string Phone { get; set; }
        // Адрес электронной почты человека.
        public string Email { get; set; }
        // Конструктор вызывается при создании нового объекта Contact.
        // В него передаются все данные, которые нужно сохранить в контакте.
        public Contact(int id, string name, string phone, string email)
        {
            // Сохраняем переданный идентификатор.
            Id = id;
            // Сохраняем имя человека.
            Name = name;
            // Сохраняем телефон.
            Phone = phone;
            // Сохраняем электронную почту.
            Email = email;
        }
    }
}
